package DatatypesAndOperator;

public class DivisonOfDatatypes {
    public static void main(String[] args) {
        double x=5/2;
        System.out.println(x);
        double y=5.0/2;
        double z=4.0/2.0;
        double w=3/2.5;
        System.out.println(y);
        System.out.println(z);
        System.out.println(w);
    }
}
