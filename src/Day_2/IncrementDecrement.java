package Day_2;
public class IncrementDecrement {
    public static void main(String[] args) {
        int ball=12;
        System.out.println(ball);
        ball+=5;// ball=ball+2
        System.out.println(ball);
        int x=11;
        System.out.println(x);
        x++;
        System.out.println(x);
        ++x;
        System.out.println(x);
        x--;
        System.out.println(x);
        --x;
        System.out.println(x);
        int b=2;
        System.out.println(b++);//post increment
        System.out.println(b);
        int w=7;
        int v=w++;//v=7
        System.out.println(w+" "+v);
    }

}
