package Basic_java;

public class ArithematicOperator {
    public static void main(String[] args) {
        int x=35,y=600;
        System.out.println(x+y);
        System.out.println(x-y);
        System.out.println(x*y);
        System.out.println(x/y);
        double a=39,b=60;
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
    }
}
