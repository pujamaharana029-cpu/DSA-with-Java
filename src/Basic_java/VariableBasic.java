package Basic_java;

public class VariableBasic {
    public static void main(String[] args) {
        int a=3;
        System.out.println(a);
        a=a+42;
        System.out.println(a);
        int y; //declaration
        y=34;//intialization
        System.out.println(y);
        a=a-29;
        System.out.println(a);
        a=a*12;
        System.out.println(a);
        a=a/23;
        System.out.println(a);

    }
}
