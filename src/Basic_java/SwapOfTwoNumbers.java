package Basic_java;

public class SwapOfTwoNumbers {
    public static void main(String[] args) {
        int a=10;
        int b=30;
        System.out.println("before swapping the two numbers are a="+a+ "and b ="+b);
        int temp=a;
        a=b;
        b=temp;
        System.out.println("after swapping the two numbers are a="+a+"and b ="+b);
    }

}


